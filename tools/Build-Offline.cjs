'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const zlib=require('node:zlib');
const root=path.resolve(__dirname,'..');
const languages=require('../assets/languages.js');
const urls=new Set(['/','/privacy/','/privacy/da/','/manifest.webmanifest']);
function add(url){urls.add(url);}
// No generated share pages or personal URLs enter the cache.
for(const code of ['',...languages.map(l=>l.code)]){
 const file=code?`${code}/index.html`:'index.html';
 add(code?`/${code}/`:'/');
 const html=fs.readFileSync(path.join(root,file),'utf8');
 for(const m of html.matchAll(/(?:src|href)="((?:assets|images)\/[^"#]+)"/g))add('/'+m[1]);
}
function walk(dir){for(const entry of fs.readdirSync(path.join(root,dir),{withFileTypes:true})){
 const name=dir+'/'+entry.name;
 if(entry.isDirectory())walk(name);
 else if(/\.(png|svg|jpg|webp)$/.test(name))add('/'+name);
}}
walk('tests');walk('images');
const entries=[...urls].sort();
const digest=crypto.createHash('sha256');let bytes=0;const files=[];
const mime={'.html':'text/html; charset=utf-8','.js':'text/javascript; charset=utf-8','.css':'text/css; charset=utf-8','.svg':'image/svg+xml','.png':'image/png','.jpg':'image/jpeg','.webp':'image/webp','.webmanifest':'application/manifest+json'};
digest.update(fs.readFileSync(path.join(root,'service-worker.js')));
for(const url of entries){let file=url.split('?')[0].slice(1);if(!file||file.endsWith('/'))file+='index.html';const body=fs.readFileSync(path.join(root,file));digest.update(url).update(body);bytes+=body.length;files.push([url,mime[path.extname(file)]||'application/octet-stream',body.toString('base64')]);}
const revision=digest.digest('hex').slice(0,20);
const payload=Buffer.from(JSON.stringify(files)),bundle=zlib.gzipSync(payload,{level:9});
const output='// Generated by tools/Build-Offline.cjs. Public, product-owned assets only.\nself.IQ_OFFLINE='+JSON.stringify({revision,urls:entries,bundle:{url:'/assets/offline-bundle.bin?v='+revision,sha256:crypto.createHash('sha256').update(payload).digest('hex')}},null,2)+';\n';
const dest=path.join(root,'assets/offline-manifest.js');
const bundleDest=path.join(root,'assets/offline-bundle.bin');
if(process.argv.includes('--check')){if(!fs.existsSync(dest)||fs.readFileSync(dest,'utf8')!==output||!fs.existsSync(bundleDest)||!fs.readFileSync(bundleDest).equals(bundle))throw Error('Offline snapshot is stale');}
else {fs.writeFileSync(dest,output);fs.writeFileSync(bundleDest,bundle);}
console.log(JSON.stringify({revision,entries:entries.length,bytes,bundleBytes:bundle.length}));
